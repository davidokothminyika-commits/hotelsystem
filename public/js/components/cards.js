/**
 * public/js/components/cards.js
 *
 * WHAT THIS MODULE DOES
 * Reusable renderers for the repeated card patterns: rooms, bookings, menu
 * items, orders and reviews.
 *
 * WHY THIS EXISTS
 * The rooms page, the booking list, the restaurant and the dashboard all need
 * to show a room or a booking. Writing that markup once means the card stays
 * consistent and a design change is a single edit.
 *
 * THE RENDERING RULE
 * Every function here builds elements and appends text nodes. API data is
 * never passed to innerHTML, so a guest who types
 * `<img onerror=...>` into a special request field cannot inject script when
 * an administrator views the booking.
 *
 * COMMUNICATION
 * Pages -> this module -> returns an HTMLElement to append
 */
import { createElement, formatMoney, formatDate, statusBadge } from '../lib/dom.js';

/**
 * A statistic tile for dashboards.
 *
 * @param {object} options
 * @param {string} options.label
 * @param {string|number} options.value
 * @param {string} [options.icon]
 * @param {'neutral'|'success'|'warning'|'danger'|'info'|'accent'} [options.tone='neutral']
 * @param {string} [options.hint] Small supporting text.
 * @param {string} [options.href] Makes the whole tile a link.
 */
export function statCard({ label, value, icon, tone = 'neutral', hint, href }) {
    // Complete class literals from a fixed map. An interpolated class name
    // would not be generated by the Tailwind CDN and would render unstyled.
    const TONES = {
        neutral: { wrap: 'bg-stone-100 text-stone-600', icon: 'bg-stone-200 text-stone-700' },
        success: { wrap: 'bg-green-100 text-green-700', icon: 'bg-green-200 text-green-800' },
        warning: { wrap: 'bg-amber-100 text-amber-700', icon: 'bg-amber-200 text-amber-800' },
        danger: { wrap: 'bg-red-100 text-red-700', icon: 'bg-red-200 text-red-800' },
        info: { wrap: 'bg-blue-100 text-blue-700', icon: 'bg-blue-200 text-blue-800' },
        accent: { wrap: 'bg-purple-100 text-purple-700', icon: 'bg-purple-200 text-purple-800' },
    };

    const theme = TONES[tone] || TONES.neutral;

    const card = document.createElement(href ? 'a' : 'div');
    card.className = 'card card-hover p-5 flex items-start gap-4';
    if (href) card.href = href;

    if (icon) {
        const badge = createElement('span', {
            class: `flex items-center justify-center w-11 h-11 rounded-lg shrink-0 ${theme.icon}`,
        });
        const iconEl = createElement('i', { class: `fa-solid ${icon}`, 'aria-hidden': 'true' });
        badge.appendChild(iconEl);
        card.appendChild(badge);
    }

    const body = document.createElement('div');
    body.className = 'min-w-0';

    body.appendChild(createElement('p', { class: 'text-xs font-medium text-stone-500 uppercase tracking-wide', text: label }));

    // The value is a number from the API; textContent keeps it inert.
    const valueEl = document.createElement('p');
    valueEl.className = 'text-2xl font-bold text-stone-900 mt-1 truncate';
    valueEl.textContent = typeof value === 'number' ? value.toLocaleString() : String(value);
    body.appendChild(valueEl);

    if (hint) {
        body.appendChild(createElement('p', { class: 'text-xs text-stone-500 mt-1', text: hint }));
    }

    card.appendChild(body);
    return card;
}

/**
 * A room card for the availability results grid.
 *
 * @param {object} room
 * @param {(room: object) => void} [onBook] Called when "Book now" is clicked.
 */
export function roomCard(room, onBook) {
    const card = createElement('article', { class: 'card card-hover overflow-hidden flex flex-col' });

    // ---- Image ----
    const figure = document.createElement('div');
    figure.className = 'relative h-48 bg-stone-200';

    if (room.image) {
        const img = createElement('img', {
            src: room.image,
            alt: `${room.roomType?.name || 'Room'} ${room.roomNumber}`,
            class: 'w-full h-full object-cover',
            loading: 'lazy',
        });
        // A missing image should leave the gradient rather than a broken icon.
        img.addEventListener('error', () => img.remove(), { once: true });
        figure.appendChild(img);
    } else {
        const placeholder = createElement('div', {
            class: 'w-full h-full bg-gradient-to-br from-stone-200 to-stone-100 flex items-center justify-center',
        });
        placeholder.appendChild(
            createElement('i', { class: 'fa-solid fa-bed text-4xl text-stone-400', 'aria-hidden': 'true' }),
        );
        figure.appendChild(placeholder);
    }

    const statusWrap = document.createElement('div');
    statusWrap.className = 'absolute top-3 right-3';
    statusWrap.appendChild(statusBadge(room.status));
    figure.appendChild(statusWrap);

    card.appendChild(figure);

    // ---- Body ----
    const body = createElement('div', { class: 'card-body flex-1' });

    body.appendChild(
        createElement('h3', { class: 'text-lg font-semibold text-stone-900', text: room.roomType?.name || 'Room' }),
    );

    const meta = document.createElement('p');
    meta.className = 'text-xs text-stone-500 mt-0.5 flex items-center gap-2 flex-wrap';
    meta.appendChild(createElement('span', { text: `Room ${room.roomNumber}` }));
    meta.appendChild(createElement('span', { class: 'text-stone-300', text: '|' }));
    meta.appendChild(createElement('span', { class: 'flex items-center gap-1', text: `Sleeps ${room.capacity}` }));
    if (room.roomType?.sizeSqm) {
        meta.appendChild(createElement('span', { class: 'text-stone-300', text: '|' }));
        meta.appendChild(createElement('span', { text: `${room.roomType.sizeSqm} m2` }));
    }
    body.appendChild(meta);

    if (room.roomType?.bedConfiguration) {
        body.appendChild(
            createElement('p', {
                class: 'text-xs text-stone-500 mt-2 flex items-center gap-1.5',
                text: room.roomType.bedConfiguration,
            }),
        );
    }

    if (room.description) {
        body.appendChild(
            createElement('p', { class: 'text-sm text-stone-500 mt-2 line-clamp-2', text: room.description }),
        );
    }

    // ---- Amenities ----
    if (Array.isArray(room.amenities) && room.amenities.length > 0) {
        const list = createElement('ul', { class: 'flex flex-wrap gap-1.5 mt-3' });
        for (const amenity of room.amenities.slice(0, 4)) {
            list.appendChild(
                createElement('li', {
                    class: 'text-[11px] px-2 py-0.5 rounded bg-stone-100 text-stone-600 flex items-center gap-1',
                }, [
                    createElement('i', {
                        class: `fa-solid ${amenity.icon || 'fa-check'} text-[10px] text-stone-400`,
                        'aria-hidden': 'true',
                    }),
                    document.createTextNode(amenity.name),
                ]),
            );
        }
        if (room.amenities.length > 4) {
            list.appendChild(createElement('li', {
                class: 'text-[11px] px-2 py-0.5 rounded bg-stone-100 text-stone-500',
                text: `+${room.amenities.length - 4} more`,
            }));
        }
        body.appendChild(list);
    }

    card.appendChild(body);

    // ---- Footer with price and action ----
    const footer = createElement('div', { class: 'card-footer flex items-center justify-between gap-3' });

    const priceWrap = document.createElement('div');

    if (room.stayTotal) {
        // Total for the requested stay, with the nightly rate underneath.
        priceWrap.appendChild(
            createElement('p', { class: 'text-lg font-bold text-stone-900', text: formatMoney(room.stayTotal) }),
        );
        priceWrap.appendChild(
            createElement('p', {
                class: 'text-xs text-stone-500',
                text: `total for ${room.nights || ''} night stay`.trim(),
            }),
        );
    } else {
        priceWrap.appendChild(
            createElement('p', {
                class: 'text-lg font-bold text-stone-900',
                text: formatMoney(room.pricePerNight),
            }),
        );
        priceWrap.appendChild(createElement('p', { class: 'text-xs text-stone-500', text: 'per night' }));
    }

    const actions = document.createElement('div');
    actions.className = 'flex items-center gap-2';

    const details = createElement('a', {
        href: `/pages/guest/room-details.html?id=${room.id}`,
        class: 'btn btn-outline btn-sm',
        text: 'Details',
    });

    const bookButton = createElement('button', {
        type: 'button',
        class: 'btn btn-primary btn-sm',
        text: 'Book now',
    });
    if (onBook) {
        bookButton.addEventListener('click', () => onBook(room));
    }

    actions.append(details, bookButton);
    footer.append(priceWrap, actions);
    card.appendChild(footer);

    return card;
}

/**
 * A booking row/card.
 *
 * @param {object} booking
 * @param {object} [actions] Map of action name to { label, variant, onClick }.
 */
export function bookingCard(booking, actions = {}) {
    const card = createElement('article', { class: 'card p-5' });

    // ---- Header: reference and status ----
    const header = createElement('div', { class: 'flex flex-wrap items-start justify-between gap-3 mb-4' });

    const left = document.createElement('div');

    const refRow = document.createElement('div');
    refRow.className = 'flex items-center gap-2 flex-wrap';
    refRow.appendChild(
        createElement('span', { class: 'font-mono text-sm font-semibold text-stone-900', text: booking.bookingReference }),
    );
    refRow.appendChild(statusBadge(booking.status));
    left.appendChild(refRow);

    left.appendChild(
        createElement('p', {
            class: 'text-sm text-stone-500 mt-1',
            text: `${booking.roomType || 'Room'} ${booking.roomNumber || ''}`.trim(),
        }),
    );

    if (booking.guestName && booking.guestEmail) {
        left.appendChild(
            createElement('p', {
                class: 'text-xs text-stone-400 mt-0.5',
                text: `${booking.guestName} - ${booking.guestEmail}`,
            }),
        );
    }

    header.appendChild(left);

    const amount = document.createElement('div');
    amount.className = 'text-right';
    amount.appendChild(
        createElement('p', { class: 'text-lg font-bold text-stone-900', text: formatMoney(booking.totalAmount) }),
    );
    if (Number(booking.balanceDue) > 0) {
        amount.appendChild(
            createElement('p', {
                class: 'text-xs text-amber-700 font-medium',
                text: `${formatMoney(booking.balanceDue)} outstanding`,
            }),
        );
    }
    header.appendChild(amount);
    card.appendChild(header);

    // ---- Stay dates ----
    const dates = createElement('div', {
        class: 'flex items-center gap-3 text-sm text-stone-600 mb-4 pb-4 border-b border-stone-100 flex-wrap',
    });

    const stay = document.createElement('div');
    const inDate = createElement('p', { class: 'font-medium text-stone-900', text: formatDate(booking.checkIn) });
    const inLabel = createElement('p', { class: 'text-xs text-stone-500', text: 'Check in' });
    stay.append(inLabel, inDate);

    const nights = document.createElement('div');
    nights.className = 'text-xs text-stone-400 flex items-center gap-1.5';
    nights.appendChild(
        createElement('i', { class: 'fa-solid fa-arrow-right', 'aria-hidden': 'true' }),
    );
    nights.appendChild(
        createElement('span', { text: `${booking.nights} night${Number(booking.nights) === 1 ? '' : 's'}` }),
    );

    const outDate = document.createElement('div');
    outDate.className = 'text-right';
    outDate.appendChild(createElement('p', { class: 'font-medium text-stone-900', text: formatDate(booking.checkOut) }));
    outDate.appendChild(createElement('p', { class: 'text-xs text-stone-500', text: 'Check out' }));

    dates.append(stay, nights, outDate);

    if (booking.guests) {
        dates.appendChild(
            createElement('span', {
                class: 'text-xs text-stone-500 flex items-center gap-1.5 ml-auto',
            }, [
                createElement('i', { class: 'fa-solid fa-users', 'aria-hidden': 'true' }),
                document.createTextNode(`${booking.guests} guest${Number(booking.guests) === 1 ? '' : 's'}`),
            ]),
        );
    }

    card.appendChild(dates);

    // ---- Actions ----
    const actionKeys = Object.keys(actions);
    if (actionKeys.length > 0) {
        const bar = createElement('div', { class: 'flex flex-wrap items-center gap-2' });

        const VARIANTS = {
            primary: 'btn btn-primary btn-sm',
            outline: 'btn btn-outline btn-sm',
            danger: 'btn btn-danger btn-sm',
            ghost: 'btn btn-ghost btn-sm',
        };

        for (const key of actionKeys) {
            const action = actions[key];
            if (!action) continue;

            const button = createElement('button', {
                type: 'button',
                class: VARIANTS[action.variant] || VARIANTS.outline,
                text: action.label,
            });
            if (action.icon) {
                button.prepend(createElement('i', { class: `fa-solid ${action.icon} mr-2`, 'aria-hidden': 'true' }));
            }
            button.addEventListener('click', () => action.onClick(booking));
            bar.appendChild(button);
        }

        const view = createElement('a', {
            href: `/pages/guest/booking-details.html?id=${booking.id}`,
            class: 'btn btn-ghost btn-sm ml-auto',
            text: 'View details',
        });
        bar.appendChild(view);

        card.appendChild(bar);
    }

    return card;
}

/**
 * A menu item card for the restaurant page.
 *
 * @param {object} item
 * @param {(item: object) => void} [onAdd]
 */
export function menuItemCard(item, onAdd) {
    const card = createElement('article', { class: 'card card-hover overflow-hidden flex flex-col' });

    // ---- Image ----
    const figure = document.createElement('div');
    figure.className = 'relative h-40 bg-stone-200';

    if (item.image) {
        const img = createElement('img', {
            src: item.image,
            alt: item.name,
            class: 'w-full h-full object-cover',
            loading: 'lazy',
        });
        img.addEventListener('error', () => img.remove(), { once: true });
        figure.appendChild(img);
    } else {
        const placeholder = createElement('div', {
            class: 'w-full h-full bg-gradient-to-br from-amber-50 to-stone-100 flex items-center justify-center',
        });
        placeholder.appendChild(
            createElement('i', { class: 'fa-solid fa-utensils text-3xl text-stone-300', 'aria-hidden': 'true' }),
        );
        figure.appendChild(placeholder);
    }

    // Flags for dietary information, which guests filter by.
    const flags = document.createElement('div');
    flags.className = 'absolute top-2 left-2 flex gap-1.5 flex-wrap';
    if (item.is_vegetarian) {
        flags.appendChild(
            createElement('span', {
                class: 'badge badge-success',
                title: 'Vegetarian',
                text: 'Veg',
            }),
        );
    }
    if (item.is_spicy) {
        flags.appendChild(
            createElement('span', {
                class: 'badge badge-danger',
                title: 'Spicy',
                text: 'Spicy',
            }),
        );
    }
    if (!item.is_available) {
        flags.appendChild(createElement('span', { class: 'badge badge-neutral', text: 'Sold out' }));
    }
    figure.appendChild(flags);

    card.appendChild(figure);

    // ---- Body ----
    const body = createElement('div', { class: 'card-body flex-1' });

    const titleRow = createElement('div', { class: 'flex items-start justify-between gap-3 mb-1.5' });
    titleRow.appendChild(createElement('h3', { class: 'font-semibold text-stone-900', text: item.name }));
    titleRow.appendChild(
        createElement('span', { class: 'text-sm font-bold text-stone-900 shrink-0', text: formatMoney(item.price) }),
    );
    body.appendChild(titleRow);

    if (item.category_name) {
        body.appendChild(createElement('p', { class: 'text-xs text-stone-400', text: item.category_name }));
    }

    if (item.description) {
        body.appendChild(
            createElement('p', { class: 'text-sm text-stone-500 mt-2 line-clamp-2 leading-relaxed', text: item.description }),
        );
    }

    if (item.prep_minutes) {
        body.appendChild(
            createElement('p', {
                class: 'text-xs text-stone-400 mt-2 flex items-center gap-1.5',
                text: `Prepared in about ${item.prep_minutes} minutes`,
            }),
        );
    }

    card.appendChild(body);

    // ---- Add to cart ----
    const footer = createElement('div', { class: 'card-footer' });

    const button = createElement('button', {
        type: 'button',
        class: 'btn btn-primary btn-block btn-sm',
        text: 'Add to order',
    });
    button.prepend(createElement('i', { class: 'fa-solid fa-plus mr-2', 'aria-hidden': 'true' }));

    if (!item.is_available) {
        button.disabled = true;
        button.textContent = 'Sold out';
    } else if (onAdd) {
        button.addEventListener('click', () => onAdd(item));
    }

    footer.appendChild(button);
    card.appendChild(footer);

    return card;
}

/**
 * A review card.
 */
export function reviewCard(review, { showEntity = false } = {}) {
    const card = createElement('article', { class: 'card p-5 flex flex-col' });

    // ---- Rating stars ----
    const rating = Number(review.rating) || 0;
    const stars = createElement('div', {
        class: 'flex gap-0.5 mb-2',
        'aria-label': `${rating} out of 5 stars`,
    });
    for (let i = 1; i <= 5; i += 1) {
        stars.appendChild(
            createElement('i', {
                // Two complete literals chosen by comparison, not interpolation.
                class: i <= rating ? 'fa-solid fa-star text-amber-500 text-xs' : 'fa-regular fa-star text-stone-300 text-xs',
                'aria-hidden': 'true',
            }),
        );
    }
    card.appendChild(stars);

    card.appendChild(createElement('h3', { class: 'font-semibold text-stone-900 mb-1.5', text: review.title }));
    card.appendChild(createElement('p', { class: 'text-sm text-stone-600 leading-relaxed flex-1', text: review.comment }));

    // ---- Management reply ----
    if (review.staff_reply) {
        const reply = createElement('div', { class: 'mt-3 pl-3 border-l-2 border-amber-400 bg-amber-50/50 rounded-r p-3' });
        reply.appendChild(
            createElement('p', { class: 'text-xs font-semibold text-amber-800 mb-1', text: 'Response from Aurelia Grand' }),
        );
        reply.appendChild(createElement('p', { class: 'text-xs text-stone-600', text: review.staff_reply }));
        card.appendChild(reply);
    }

    // ---- Byline ----
    const byline = createElement('div', {
        class: 'flex flex-wrap items-center justify-between gap-2 mt-4 pt-3 border-t border-stone-100 text-xs text-stone-400',
    });
    byline.appendChild(
        createElement('span', { class: 'font-medium text-stone-600', text: review.userName || 'Verified guest' }),
    );

    if (showEntity && review.entity_type) {
        byline.appendChild(
            createElement('span', {
                class: 'capitalize',
                text: review.entity_type.replace('_', ' '),
            }),
        );
    }

    byline.appendChild(
        createElement('span', {
            text: review.createdAt ? new Date(review.createdAt).toLocaleDateString() : '',
        }),
    );

    card.appendChild(byline);
    return card;
}

/**
 * A paginator.
 *
 * @param {object} options
 * @param {number} options.page
 * @param {number} options.totalPages
 * @param {number} options.total
 * @param {(page: number) => void} options.onChange
 */
export function pagination({ page, totalPages, total, onChange }) {
    const nav = createElement('nav', {
        class: 'flex flex-wrap items-center justify-between gap-3 pt-4',
        'aria-label': 'Pagination',
    });

    const summary = createElement('p', { class: 'text-sm text-stone-500' });
    summary.textContent = total > 0 ? `Showing page ${page} of ${totalPages}` : 'No results';
    nav.appendChild(summary);

    if (totalPages <= 1) return nav;

    const controls = createElement('div', { class: 'flex items-center gap-1' });

    const previous = createElement('button', {
        type: 'button',
        class: 'btn btn-outline btn-sm',
        'aria-label': 'Previous page',
    }, [createElement('i', { class: 'fa-solid fa-chevron-left', 'aria-hidden': 'true' })]);
    previous.disabled = page <= 1;
    previous.addEventListener('click', () => onChange(page - 1));

    const next = createElement('button', {
        type: 'button',
        class: 'btn btn-outline btn-sm',
        'aria-label': 'Next page',
    }, [createElement('i', { class: 'fa-solid fa-chevron-right', 'aria-hidden': 'true' })]);
    next.disabled = page >= totalPages;
    next.addEventListener('click', () => onChange(page + 1));

    controls.append(previous, next);
    nav.appendChild(controls);

    return nav;
}

export default { statCard, roomCard, bookingCard, menuItemCard, reviewCard, pagination };